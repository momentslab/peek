"""Selectors must pick exactly the frames the paper runs picked.

``paper_selectors.json`` was generated by running the selection functions of
the code that produced the paper tables on the same inputs.
"""
import json
from pathlib import Path

from peek.eval.selectors import linspace_cap, random_bucketed_indices, random_seed, uniform_indices

EXPECTED = json.loads((Path(__file__).parent / "paper_selectors.json").read_text())


def _cases(table):
    for key, value in EXPECTED[table].items():
        yield tuple(int(x) for x in key.split(",")), value


def test_uniform():
    for (n, k), expected in _cases("uniform"):
        assert uniform_indices(n, k) == expected, (n, k)


def test_random_anc():
    for (n, k), expected in _cases("anc_random"):
        seed = random_seed("anc", base_seed=0, video_id="v_--1DO2V4K74", segment_id="val1_seg_00000", k=k)
        assert random_bucketed_indices(n, k, seed) == expected, (n, k)


def test_random_msrvtt():
    for (n, k), expected in _cases("msrvtt_random"):
        seed = random_seed("msrvtt", base_seed=0, video_id="video7010", segment_id="video7010", k=k)
        assert random_bucketed_indices(n, k, seed) == expected, (n, k)


def test_peek_frame_cap():
    for (n,), expected in _cases("cap32"):
        assert linspace_cap(n, 32) == expected, n
    assert linspace_cap(81, None) == list(range(81))
